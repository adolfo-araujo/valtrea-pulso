package br.com.valtrea.pulso.iniciativa;

public enum MotivoDenuncia {
	/** Xingamento, ataque ou preconceito contra alguém. */
	OFENSIVO,
	/** Expõe uma pessoa: nome, endereço, telefone ou foto de alguém. */
	DADOS_PESSOAIS,
	/** Propaganda, venda ou pedido de voto. */
	PROPAGANDA,
	/** Repetida, sem sentido ou de outro bairro. */
	SPAM,
	/** Informação falsa ou golpe. */
	FALSO,
	OUTRO
}
